const groupTargets = {
  web: document.querySelector('#web-projects'),
  graphics: document.querySelector('#graphic-projects'),
  games: document.querySelector('#game-projects')
};

// Creates each card and places it in the right portfolio section.
projects.forEach(project => {
  const card = document.createElement('article');
  card.className = 'project-card';
  card.innerHTML = `
    <img class="project-image ${project.imageFit === 'contain' ? 'project-image-contain' : ''}" src="${project.image}" alt="${project.imageAlt}" loading="lazy">
    <div class="card-content">
      <span class="card-number">PROJECT ${project.number}</span>
      <h3>${project.title}</h3>
      <p class="card-facts">${project.medium} · ${project.year}</p>
      <p>${project.short}</p>
      <div class="card-footer">
        <span class="card-category">${project.category}</span>
        <button class="card-button" type="button">View project details →</button>
      </div>
    </div>`;
  card.querySelector('.card-button').addEventListener('click', () => showProject(project));
  groupTargets[project.section].appendChild(card);
});

const dialog = document.querySelector('#project-dialog');
const closeButton = document.querySelector('.close-dialog');

function showProject(project) {
  document.querySelector('#dialog-title').textContent = project.title;
  const image = document.querySelector('#dialog-image');
  image.src = project.image;
  image.alt = project.imageAlt;
  const metadata = [
    ['Project number', project.number], ['Year created', project.year],
    ['Class', project.className], ['Media / tools', project.medium],
    ['Collaboration / role', project.contribution]
  ];
  const metaContainer = document.querySelector('#dialog-meta');
  metaContainer.replaceChildren();
  metadata.forEach(([label, value]) => {
    const item = document.createElement('div');
    const term = document.createElement('dt');
    const definition = document.createElement('dd');
    term.textContent = label;
    definition.textContent = value;
    item.append(term, definition);
    metaContainer.append(item);
  });
  document.querySelector('#dialog-description').textContent = project.description;
  document.querySelector('#dialog-image-note').textContent = project.imageNote;
  const demoDetails = document.querySelector('#dialog-demo');
  const demoLink = document.querySelector('#dialog-demo-link');
  document.querySelector('#dialog-demo-label').textContent = project.demoLabel || 'Try the interactive registration form';
  document.querySelector('#dialog-demo-note').textContent = project.demoNote || 'This is an included coursework demo, not a real checkout.';
  document.querySelector('#dialog-demo-frame').title = project.demoTitle || 'Embedded coursework demo';
  demoDetails.open = false;
  demoDetails.hidden = !project.demoPath;
  demoDetails.dataset.demoPath = project.demoPath || '';
  demoLink.href = project.demoPath || '#';
  document.querySelector('#dialog-demo-frame').src = 'about:blank';
  dialog.showModal();
}

// The working demo loads only when a visitor opens it, so the timer starts then.
const demoDetails = document.querySelector('#dialog-demo');
demoDetails.addEventListener('toggle', () => {
  const frame = document.querySelector('#dialog-demo-frame');
  frame.src = demoDetails.open && demoDetails.dataset.demoPath
    ? demoDetails.dataset.demoPath
    : 'about:blank';
});

closeButton.addEventListener('click', () => dialog.close());
dialog.addEventListener('close', () => {
  demoDetails.open = false;
  document.querySelector('#dialog-demo-frame').src = 'about:blank';
});
dialog.addEventListener('click', event => {
  // Clicking the dimmed area outside the dialog closes it.
  if (event.target === dialog) dialog.close();
});

// Mobile navigation: no external JavaScript library required.
const menuButton = document.querySelector('.menu-toggle');
const nav = document.querySelector('.site-nav');
menuButton.addEventListener('click', () => {
  const isOpen = nav.classList.toggle('is-open');
  menuButton.setAttribute('aria-expanded', String(isOpen));
  menuButton.setAttribute('aria-label', isOpen ? 'Close navigation menu' : 'Open navigation menu');
});
nav.querySelectorAll('a').forEach(link => link.addEventListener('click', () => {
  nav.classList.remove('is-open');
  menuButton.setAttribute('aria-expanded', 'false');
  menuButton.setAttribute('aria-label', 'Open navigation menu');
}));

document.querySelector('#copyright-year').textContent = new Date().getFullYear();
